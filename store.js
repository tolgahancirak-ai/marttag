const products = [];

const categoryKeys = ["all", "home", "fashion", "accessories", "beauty"];
const currencyFormatters = {
  ar: new Intl.NumberFormat("ar-EG", { style: "currency", currency: "EGP", maximumFractionDigits: 0 }),
  tr: new Intl.NumberFormat("tr-TR", { style: "currency", currency: "EGP", maximumFractionDigits: 0 }),
  en: new Intl.NumberFormat("en-EG", { style: "currency", currency: "EGP", maximumFractionDigits: 0 }),
};

let language = "ar";
let activeCategory = "all";
let searchQuery = "";
let deliveryFee = 0;
let apiReady = false;
let storeName = "Epgyt Market";
let formattedPhone = "+20 103 178 0616";
const cart = new Map();
let toastTimeout;

const t = (key) => translations[language][key];
const formatPrice = (price) => currencyFormatters[language].format(price);
const formatPhone = (phone) => {
  const digits = phone.replace(/\D/g, "");
  const match = digits.match(/^20(\d{3})(\d{3})(\d{4})$/);
  return match ? `+20 ${match[1]} ${match[2]} ${match[3]}` : phone;
};
const productName = (product) => product.name[language];
const productCategory = (product) => product.category_name[language];
const productImage = (product, width = 620) =>
  `https://images.unsplash.com/${product.image}?auto=format&fit=crop&w=${width}&q=80`;

function applyLanguage() {
  const copy = translations[language];
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title = language === "ar" ? `${storeName} — اكتشف اختياراتك` : `${storeName} — Thoughtful local finds`;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key]) element.textContent = copy[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = copy[element.dataset.i18nPlaceholder];
  });
  document.getElementById("search-input").setAttribute("aria-label", copy.searchPlaceholder);
  document.getElementById("cart-open").setAttribute("aria-label", copy.bagTitle);
  document.getElementById("cart-drawer").setAttribute("aria-label", copy.bagTitle);
  document.getElementById("checkout-close").setAttribute("aria-label", language === "ar" ? "إغلاق" : language === "tr" ? "Kapat" : "Close");
  document.getElementById("checkout-notice").textContent = t("apiUnavailable");
  document.getElementById("checkout-notice").hidden = apiReady;
  document.querySelectorAll("[data-store-name]").forEach((element) => { element.textContent = storeName; });
  document.querySelectorAll("[data-store-phone]").forEach((element) => { element.textContent = formattedPhone; });
  renderCategories();
  renderProducts();
  renderCart();
  renderGovernorates();
  updateCheckoutTotal();
}

function renderGovernorates() {
  const select = document.getElementById("governorate-select");
  const previousValue = select.value;
  const placeholder = document.createElement("option");
  placeholder.value = "";
  placeholder.textContent = t("chooseGovernorate");
  placeholder.disabled = true;
  placeholder.selected = true;
  select.replaceChildren(placeholder, ...t("governorates").map((governorate, index) => {
    const option = document.createElement("option");
    option.value = t("governorateCodes")[index];
    option.textContent = governorate;
    return option;
  }));
  if (previousValue) select.value = previousValue;
}

function renderCategories() {
  const list = document.getElementById("category-list");
  list.replaceChildren(...categoryKeys.map((key) => {
    const button = document.createElement("button");
    button.className = `category-button${activeCategory === key ? " active" : ""}`;
    button.type = "button";
    button.textContent = t(key);
    button.setAttribute("aria-pressed", String(activeCategory === key));
    button.addEventListener("click", () => {
      activeCategory = key;
      renderCategories();
      renderProducts();
    });
    return button;
  }));
}

function renderProducts() {
  const grid = document.getElementById("product-grid");
  const normalizedQuery = searchQuery.trim().toLocaleLowerCase(language);
  const visibleProducts = products.filter((product) => {
    const matchesCategory = activeCategory === "all" || product.category === activeCategory;
    const matchesSearch = !normalizedQuery || productName(product).toLocaleLowerCase(language).includes(normalizedQuery)
      || productCategory(product).toLocaleLowerCase(language).includes(normalizedQuery);
    return matchesCategory && matchesSearch;
  });

  if (!visibleProducts.length) {
    const empty = document.createElement("p");
    empty.className = "empty-state";
    empty.textContent = t("emptyResults");
    grid.replaceChildren(empty);
    return;
  }

  grid.replaceChildren(...visibleProducts.map((product) => {
    const card = document.createElement("article");
    card.className = "product-card";
    const image = document.createElement("div");
    image.className = "product-image";
    const img = document.createElement("img");
    img.src = productImage(product);
    img.alt = productName(product);
    img.loading = "lazy";
    img.width = 620;
    img.height = 700;
    image.append(img);

    if (product.badge) {
      const badge = document.createElement("span");
      badge.className = "product-badge";
      badge.textContent = t(product.badge === "new" ? "badgeNew" : "badgePopular");
      image.append(badge);
    }

    const add = document.createElement("button");
    add.className = "add-button";
    add.type = "button";
    add.innerHTML = `<span aria-hidden="true">+</span> ${t("add")}`;
    add.addEventListener("click", () => addToCart(product.id));
    image.append(add);

    const info = document.createElement("div");
    info.className = "product-info";
    const category = document.createElement("p");
    category.className = "product-category";
    category.textContent = productCategory(product);
    const name = document.createElement("h3");
    name.className = "product-name";
    name.textContent = productName(product);
    const bottom = document.createElement("div");
    bottom.className = "product-bottom";
    const price = document.createElement("span");
    price.className = "product-price";
    price.textContent = formatPrice(product.price);
    const rating = document.createElement("span");
    rating.className = "product-rating";
    rating.innerHTML = `<span aria-hidden="true">★</span> ${product.rating}`;
    bottom.append(price, rating);
    info.append(category, name, bottom);
    card.append(image, info);
    return card;
  }));
}

function addToCart(id) {
  if ((cart.get(id) || 0) >= 10) {
    showToast(t("maxQuantity"));
    return;
  }
  cart.set(id, (cart.get(id) || 0) + 1);
  renderCart();
  showToast(t("added"));
}

function changeQuantity(id, amount) {
  const next = (cart.get(id) || 0) + amount;
  if (next > 10) {
    showToast(t("maxQuantity"));
    return;
  }
  if (next <= 0) cart.delete(id);
  else cart.set(id, next);
  renderCart();
}

function renderCart() {
  const count = [...cart.values()].reduce((total, quantity) => total + quantity, 0);
  const subtotal = products.reduce((total, product) => total + product.price * (cart.get(product.id) || 0), 0);
  document.getElementById("cart-count").textContent = String(count);
  document.getElementById("cart-subtotal").textContent = formatPrice(subtotal);
  document.getElementById("cart-delivery").textContent = formatPrice(deliveryFee);
  document.getElementById("cart-total").textContent = formatPrice(subtotal + deliveryFee);
  document.getElementById("checkout-button").disabled = !apiReady || count === 0;
  document.getElementById("checkout-notice").hidden = apiReady;
  updateCheckoutTotal();
  const items = document.getElementById("cart-items");

  if (count === 0) {
    const empty = document.createElement("p");
    empty.className = "cart-empty";
    empty.textContent = t("emptyCart");
    items.replaceChildren(empty);
    return;
  }

  items.replaceChildren(...products.filter((product) => cart.has(product.id)).map((product) => {
    const line = document.createElement("article");
    line.className = "cart-line";
    const img = document.createElement("img");
    img.src = productImage(product, 150);
    img.alt = "";
    img.loading = "lazy";
    const details = document.createElement("div");
    const name = document.createElement("h3");
    name.textContent = productName(product);
    const price = document.createElement("p");
    price.textContent = formatPrice(product.price);
    const quantity = document.createElement("div");
    quantity.className = "quantity-control";
    const decrease = document.createElement("button");
    decrease.type = "button";
    decrease.textContent = "−";
    decrease.setAttribute("aria-label", language === "ar" ? "تقليل الكمية" : language === "tr" ? "Adedi azalt" : "Decrease quantity");
    decrease.addEventListener("click", () => changeQuantity(product.id, -1));
    const amount = document.createElement("span");
    amount.textContent = String(cart.get(product.id));
    const increase = document.createElement("button");
    increase.type = "button";
    increase.textContent = "+";
    increase.setAttribute("aria-label", language === "ar" ? "زيادة الكمية" : language === "tr" ? "Adedi artır" : "Increase quantity");
    increase.addEventListener("click", () => changeQuantity(product.id, 1));
    quantity.append(decrease, amount, increase);
    details.append(name, price, quantity);
    const lineTotal = document.createElement("span");
    lineTotal.className = "cart-line-total";
    lineTotal.textContent = formatPrice(product.price * cart.get(product.id));
    line.append(img, details, lineTotal);
    return line;
  }));
}

function updateCheckoutTotal() {
  const total = products.reduce((sum, product) => sum + product.price * (cart.get(product.id) || 0), 0);
  document.getElementById("checkout-total").textContent = formatPrice(total + deliveryFee);
  document.getElementById("place-order-button").disabled = !apiReady || cart.size === 0;
}

async function loadStoreConfig() {
  try {
    const response = await fetch("/api/config", { cache: "no-store" });
    if (!response.ok) throw new Error("Store configuration request failed");
    const config = await response.json();
    if (!Number.isSafeInteger(config.delivery_fee) || config.delivery_fee < 0 || config.cod_enabled !== true
      || typeof config.store_name !== "string" || typeof config.store_phone !== "string"
      || typeof config.store_whatsapp !== "string" || !Array.isArray(config.products)
      || config.products.length === 0) {
      throw new Error("Store configuration is invalid");
    }
    products.push(...config.products);
    deliveryFee = config.delivery_fee;
    storeName = config.store_name;
    formattedPhone = formatPhone(config.store_phone);
    document.getElementById("whatsapp-link").href = `https://wa.me/${config.store_whatsapp}`;
    apiReady = true;
  } catch {
    apiReady = false;
  }
  document.getElementById("checkout-notice").hidden = apiReady;
  document.getElementById("checkout-notice").textContent = t("apiUnavailable");
  document.querySelectorAll("[data-store-name]").forEach((element) => { element.textContent = storeName; });
  document.querySelectorAll("[data-store-phone]").forEach((element) => { element.textContent = formattedPhone; });
  document.title = language === "ar" ? `${storeName} — اكتشف اختياراتك` : `${storeName} — Thoughtful local finds`;
  renderProducts();
  renderCart();
}

function toggleDrawer(isOpen) {
  document.body.classList.toggle("drawer-open", isOpen);
  document.getElementById("cart-drawer").setAttribute("aria-hidden", String(!isOpen));
  if (isOpen) document.getElementById("cart-close").focus();
  else document.getElementById("cart-open").focus();
}

function toggleCheckout(isOpen) {
  const modal = document.getElementById("checkout-modal");
  document.body.classList.toggle("checkout-open", isOpen);
  modal.setAttribute("aria-hidden", String(!isOpen));
  if (isOpen) document.getElementById("checkout-close").focus();
  else document.getElementById("cart-open").focus();
}

