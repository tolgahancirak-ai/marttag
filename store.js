document.getElementById("checkout-form").addEventListener("submit", async (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  if (!form.reportValidity() || !apiReady || cart.size === 0) return;
  const result = document.getElementById("checkout-result");
  const submitButton = document.getElementById("place-order-button");
  const customer = Object.fromEntries(new FormData(form).entries());
  const payload = {
    customer: {
      name: customer.name,
      phone: customer.phone,
      governorate: customer.governorate,
      address: customer.address,
    },
    privacy_consent: customer.privacy_consent === "accepted",
    payment_method: "cod",
    items: [...cart.entries()].map(([id, quantity]) => ({ id, quantity })),
  };
  submitButton.disabled = true;
  result.textContent = t("orderSending");
  result.hidden = false;
  try {
    const response = await fetch("/api/orders", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
    if (!response.ok) throw new Error("Order submission failed");
    const data = await response.json();
    result.textContent = `${t("orderSuccess")} ${data.order.id}`;
    cart.clear();
    form.reset();
    renderCart();
  } catch {
    result.textContent = t("orderFailed");
    submitButton.disabled = false;
  }
});
